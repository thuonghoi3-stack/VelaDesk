import { chromium } from 'playwright';
import { mkdirSync, writeFileSync, readFileSync } from 'node:fs';
import assert from 'node:assert/strict';
const base=process.env.VELA_QA_URL||'http://127.0.0.1:8080/';
const browser=await chromium.launch({headless:true});
const context=await browser.newContext({viewport:{width:1440,height:1000},acceptDownloads:true});
const page=await context.newPage(); const errors=[]; const checks=[];
page.on('pageerror',e=>errors.push(e.message));
const key='veladesk.playbook.v1';
const notebook=()=>page.evaluate(k=>JSON.parse(localStorage.getItem(k)),key);
try {
 await page.goto(base,{waitUntil:'networkidle'});
 await page.getByRole('button',{name:'Run experiment',exact:true}).waitFor();
 await page.getByLabel('Tên playbook',{exact:false}).fill('Blog demo · EMA hypothesis');
 await page.getByLabel('Giả thuyết có thể kiểm chứng',{exact:false}).fill('EMA cross có duy trì kết quả ở holdout sau chi phí?');
 await page.getByRole('button',{name:'Run experiment',exact:true}).click();
 await page.waitForFunction(k=>JSON.parse(localStorage.getItem(k)||'{}').runs?.length===1,key);
 const first=(await notebook()).runs[0]; assert.equal(first.provenance.source,'synthetic'); assert.equal(first.config.strategyId,'ema_cross'); checks.push('first run executes engine with visible synthetic provenance');
 await page.getByLabel('Tên playbook',{exact:false}).fill('Blog demo · RSI challenger');
 await page.getByLabel('Thuật toán thực thi',{exact:false}).selectOption('rsi_reversion');
 await page.getByLabel('Giả thuyết có thể kiểm chứng',{exact:false}).fill('RSI hồi quy có duy trì kết quả ở holdout sau chi phí?');
 await page.getByRole('button',{name:'Run experiment',exact:true}).click();
 await page.waitForFunction(k=>JSON.parse(localStorage.getItem(k)||'{}').runs?.length===2,key);
 const second=(await notebook()).runs[0]; assert.deepEqual((await notebook()).runs[1],first); checks.push('second run preserves first snapshot bit-for-bit');
 await page.getByLabel('So sánh holdout với bản đã lưu',{exact:false}).selectOption(first.id);
 await page.getByText('Δ Sharpe OOS',{exact:false}).waitFor(); checks.push('comparison renders');
 const downloadPromise=page.waitForEvent('download');
 await page.getByRole('button',{name:'Xuất notebook',exact:true}).click();
 const download=await downloadPromise; mkdirSync('screenshots',{recursive:true}); await download.saveAs('screenshots/playbook-notebook-export.json');
 const exported=JSON.parse(readFileSync('screenshots/playbook-notebook-export.json','utf8')); assert.deepEqual(exported.runs.map(r=>r.id),[second.id,first.id]); checks.push('actual browser JSON download contains both run IDs');
 await page.screenshot({path:'screenshots/playbook-desktop.png',fullPage:true});
 await page.reload({waitUntil:'networkidle'}); await page.getByLabel('Tên playbook',{exact:false}).waitFor();
 await page.waitForFunction(k=>JSON.parse(localStorage.getItem(k)||'{}').runs?.length===2,key);
 assert.equal(await page.getByLabel('Tên playbook',{exact:false}).inputValue(),'Blog demo · RSI challenger');
 await page.getByRole('button',{name:'JSON run',exact:true}).waitFor(); checks.push('reload restores draft and historical results');
 await page.setViewportSize({width:390,height:844}); await page.screenshot({path:'screenshots/playbook-mobile.png',fullPage:true});
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1); assert.equal(overflow,false); checks.push('390px mobile no horizontal page overflow');
 assert.deepEqual(errors,[]); checks.push('no uncaught browser errors');
 const verdict={ok:true,url:base,checks,errors,export:'screenshots/playbook-notebook-export.json'}; writeFileSync('screenshots/playbook-qa.json',JSON.stringify(verdict,null,2)); console.log(JSON.stringify(verdict,null,2));
} finally {await browser.close();}
